#!/usr/bin/env python3
"""Host execution adapter for Dynaxis Web Admin Console v3.

Polls the allowlisted control-plane queue (`POST /api/v1/operations/worker/claim`),
validates operation targets and non-secret managed config parameters locally,
invokes `scripts/deploy_docker.ps1` with explicit allowlisted arguments (`shell=False`),
and reports command results back without ever mounting `docker.sock` inside containers.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANAGED_ENV_REL = "docker/stack/.env.managed"

ALLOWED_SERVICE_RE = re.compile(r"^(gateway-[1-9][0-9]*|server-[1-9][0-9]*|wb_worker)$")
ALLOWED_OPERATION_TYPES = frozenset({"service_restart", "config_apply", "config_rollback"})
ALLOWED_MANAGED_ENV_KEYS = (
    "SESSION_CONTINUITY_ENABLED",
    "SESSION_CONTINUITY_LEASE_TTL_SEC",
    "SERVER_DRAIN_TIMEOUT_MS",
    "RUNTIME_TRACING_ENABLED",
    "RUNTIME_TRACING_SAMPLE_PERCENT",
)
ALLOWED_ENV_VAL_RE = re.compile(r"^[0-9]{1,9}$")
SECRET_URI_RE = re.compile(r"([a-zA-Z][a-zA-Z0-9+.-]*://)[^@\s/]+@")


def sanitize_output(text: str, secret_token: str = "", max_len: int = 500) -> str:
    cleaned = SECRET_URI_RE.sub(r"\1<redacted>@", text or "")
    if secret_token:
        cleaned = cleaned.replace(secret_token, "<redacted>")
    cleaned = " ".join(cleaned.split())
    if len(cleaned) > max_len:
        cleaned = cleaned[: max_len - 3] + "..."
    return cleaned


def validate_service_name(name: object) -> str:
    if not isinstance(name, str) or not ALLOWED_SERVICE_RE.fullmatch(name):
        raise ValueError(f"Service name '{name}' is outside adapter allowlist.")
    return name


def validate_operation_plan(operation: dict[str, Any]) -> tuple[str, list[str], dict[str, str]]:
    if not isinstance(operation, dict):
        raise ValueError("Operation payload must be a JSON object.")
    op_type = operation.get("operation_type")
    if not isinstance(op_type, str) or op_type not in ALLOWED_OPERATION_TYPES:
        raise ValueError(f"Unsupported operation_type: {op_type}")

    params = operation.get("params")
    if not isinstance(params, dict):
        params = {}

    if op_type == "service_restart":
        target = validate_service_name(operation.get("target_service"))
        return op_type, [target], {}

    raw_services = params.get("affected_services")
    if not isinstance(raw_services, list) or not raw_services:
        raise ValueError("Config operation requires non-empty affected_services list.")
    services = [validate_service_name(s) for s in raw_services]

    raw_env = params.get("managed_env")
    if not isinstance(raw_env, dict):
        raise ValueError("Config operation requires managed_env dictionary.")

    managed_env: dict[str, str] = {}
    allowed_set = set(ALLOWED_MANAGED_ENV_KEYS)
    for k, v in raw_env.items():
        if k not in allowed_set:
            raise ValueError(f"Managed env key '{k}' is forbidden or unknown.")
        val_str = str(v)
        if not ALLOWED_ENV_VAL_RE.fullmatch(val_str):
            raise ValueError(f"Managed env value for '{k}' must be bounded ASCII digits.")
        managed_env[k] = val_str

    return op_type, services, managed_env


def build_execution_commands(
    operation: dict[str, Any],
    env_file_rel: str = DEFAULT_MANAGED_ENV_REL,
) -> tuple[list[list[str]], dict[str, str]]:
    op_type, services, managed_env = validate_operation_plan(operation)
    if op_type == "service_restart":
        return [
            ["pwsh", "scripts/deploy_docker.ps1", "-Action", "restart", "-Service", services[0]]
        ], {}

    commands: list[list[str]] = []
    for svc in services:
        commands.append(
            [
                "pwsh",
                "scripts/deploy_docker.ps1",
                "-Action",
                "up",
                "-Detached",
                "-EnvFile",
                env_file_rel,
                "-Service",
                svc,
            ]
        )
    return commands, managed_env


def write_managed_env_atomic(env_path: Path, managed_env: dict[str, str]) -> None:
    env_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Managed non-secret overrides generated by tools/admin_host_adapter.py",
    ]
    for key in ALLOWED_MANAGED_ENV_KEYS:
        if key in managed_env:
            lines.append(f"{key}={managed_env[key]}")
    payload = "\n".join(lines) + "\n"

    fd, tmp_name = tempfile.mkstemp(prefix=".env.managed.", dir=str(env_path.parent))
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(payload)
        os.replace(tmp_path, env_path)
    finally:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


def post_json(url: str, token: str, payload: dict[str, Any], timeout_sec: float = 10.0) -> tuple[int, dict[str, Any]]:
    headers = {
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout_sec) as resp:
            raw = resp.read().decode("utf-8", errors="replace")
            return resp.status, json.loads(raw) if raw else {}
    except urllib.error.HTTPError as err:
        raw = err.read().decode("utf-8", errors="replace") if err.fp else ""
        try:
            parsed = json.loads(raw) if raw else {}
        except Exception:
            parsed = {"raw": sanitize_output(raw, token)}
        return err.code, parsed


def process_one_claim(
    admin_url: str,
    token: str,
    repo_root: Path = REPO_ROOT,
    env_file_rel: str = DEFAULT_MANAGED_ENV_REL,
    dry_run: bool = False,
) -> bool:
    base = admin_url.rstrip("/")
    status, claim_res = post_json(f"{base}/api/v1/operations/worker/claim", token, {})
    if status != 200:
        raise RuntimeError(f"claim failed HTTP {status}: {sanitize_output(json.dumps(claim_res), token)}")

    if not claim_res.get("claimed"):
        return False

    op = claim_res.get("operation") or {}
    op_id = str(op.get("operation_id") or "")
    if not op_id:
        raise RuntimeError("Claimed operation missing operation_id.")

    outcome = "command_succeeded"
    summary = ""
    try:
        commands, managed_env = build_execution_commands(op, env_file_rel=env_file_rel)
        if dry_run:
            summary = sanitize_output(
                f"dry-run validated {len(commands)} command(s): {json.dumps(commands)}",
                token,
            )
            print(f"[admin_host_adapter] {summary}")
        else:
            if managed_env:
                write_managed_env_atomic(repo_root / env_file_rel, managed_env)
            for argv in commands:
                proc = subprocess.run(
                    argv,
                    cwd=str(repo_root),
                    shell=False,
                    capture_output=True,
                    text=True,
                    timeout=90,
                    check=False,
                )
                if proc.returncode != 0:
                    err_tail = proc.stderr or proc.stdout or f"exit {proc.returncode}"
                    raise RuntimeError(f"Command {argv} exited {proc.returncode}: {err_tail}")
            summary = sanitize_output(
                f"Executed {len(commands)} deploy_docker command(s) for {op.get('target_service', '')}.",
                token,
            )
    except Exception as exc:
        outcome = "command_failed"
        summary = sanitize_output(str(exc), token)

    rep_status, rep_res = post_json(
        f"{base}/api/v1/operations/{op_id}/worker-result",
        token,
        {"outcome": outcome, "summary": summary},
    )
    if rep_status != 200:
        raise RuntimeError(
            f"worker-result failed HTTP {rep_status}: {sanitize_output(json.dumps(rep_res), token)}"
        )
    print(f"[admin_host_adapter] operation={op_id} outcome={outcome}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Dynaxis Web Admin Console v3 host execution adapter.")
    parser.add_argument("--admin-url", default="http://127.0.0.1:39200", help="Base HTTP URL of admin_app.")
    parser.add_argument("--token-env", default="ADMIN_TOKEN", help="Environment variable holding admin bearer token.")
    parser.add_argument("--poll-interval-ms", type=int, default=1000, help="Loop poll interval in milliseconds.")
    parser.add_argument("--once", action="store_true", help="Claim and process at most one queued operation then exit.")
    parser.add_argument("--dry-run", action="store_true", help="Validate plan and report without running pwsh.")
    args = parser.parse_args()

    token = os.environ.get(args.token_env, "").strip()
    poll_sec = max(200, args.poll_interval_ms) / 1000.0

    if args.once:
        process_one_claim(args.admin_url, token, dry_run=args.dry_run)
        return 0

    print(f"[admin_host_adapter] polling {args.admin_url} every {poll_sec:.2f}s (dry_run={args.dry_run})")
    while True:
        try:
            did_work = process_one_claim(args.admin_url, token, dry_run=args.dry_run)
            if not did_work:
                time.sleep(poll_sec)
        except KeyboardInterrupt:
            return 0
        except Exception as exc:
            print(f"[admin_host_adapter] error: {sanitize_output(str(exc), token)}", file=sys.stderr)
            time.sleep(poll_sec)


if __name__ == "__main__":
    raise SystemExit(main())
