-- v3 허용 서비스 비동기 재시작·설정 변경 작업 원장과 스키마 기반 설정 리비전 이력을 정의하며,
-- secret_ref 비밀값 원문이나 전체 .env 본문은 저장하지 않는다.

-- 비동기 운영 작업(service_restart / config_apply / config_rollback) 상태 원장
create table if not exists admin_operations (
  id uuid primary key default gen_random_uuid(),
  operation_type varchar(48) not null check (operation_type in ('service_restart', 'config_apply', 'config_rollback')),
  target_service varchar(64) not null,
  status varchar(24) not null check (status in ('queued', 'running', 'verifying', 'succeeded', 'failed', 'timed_out')),
  actor_role varchar(32) not null,
  reason text not null,
  idempotency_key varchar(128) not null,
  params jsonb not null default '{}'::jsonb,
  blast_radius jsonb not null default '{}'::jsonb,
  step_log jsonb not null default '[]'::jsonb,
  error_message text not null default '',
  verify_deadline_at timestamptz null,
  created_at timestamptz not null default now(),
  started_at timestamptz null,
  verifying_at timestamptz null,
  finished_at timestamptz null,
  updated_at timestamptz not null default now()
);

create index if not exists idx_admin_operations_status_created
  on admin_operations (status, created_at asc);

create index if not exists idx_admin_operations_created
  on admin_operations (created_at desc);

-- 스키마 기반 비비밀 운영 설정 리비전 이력 (Before/After diff 및 롤백 기준점 추적)
create table if not exists admin_config_revisions (
  revision bigint generated by default as identity primary key,
  values jsonb not null,
  diff_summary jsonb not null default '[]'::jsonb,
  apply_mode varchar(24) not null check (apply_mode in ('runtime', 'restart_required', 'mixed', 'bootstrap')),
  actor_role varchar(32) not null,
  reason text not null,
  operation_id uuid null references admin_operations(id) on delete set null,
  rollback_of_revision bigint null,
  created_at timestamptz not null default now()
);

create index if not exists idx_admin_config_revisions_created
  on admin_config_revisions (created_at desc, revision desc);
